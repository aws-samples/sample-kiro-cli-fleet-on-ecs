/**
 * cdk-nag (AwsSolutions) on the fleet's stacks, and the reason for every finding it accepts.
 *
 * The checks run on every synth, so a change that adds a finding fails `cdk synth` and the
 * test suite rather than surfacing in a later review. Each suppression below says why the
 * finding does not apply here. Wildcard resources are accepted only where the action cannot
 * be scoped to a resource, and only on the policy that needs it: a new `Resource: *` grant
 * anywhere else is still reported.
 *
 * The benchmark and pipeline stacks are opt-in and not covered.
 */

import { Aspects, Stack } from 'aws-cdk-lib';
import { AwsSolutionsChecks, NagPackSuppression, NagSuppressions } from 'cdk-nag';

export interface FleetStacks {
  data: Stack;
  queue: Stack;
  network: Stack;
  compute: Stack;
  functions: Stack;
  observability: Stack;
}

const LAMBDA_BASIC: NagPackSuppression = {
  id: 'AwsSolutions-IAM4',
  reason:
    'AWSLambdaBasicExecutionRole grants only CloudWatch Logs writes for the function\'s own ' +
    'log group. It is the standard execution role and is not widened by this app.',
  appliesTo: ['Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole'],
};

/** Wildcards that are already scoped to one resource: an index of a table, objects in a bucket. */
const SCOPED_WILDCARDS: NagPackSuppression = {
  id: 'AwsSolutions-IAM5',
  reason:
    'Scoped wildcards generated by CDK grant methods: the indexes of one table ' +
    '(<table>/index/*), the objects in one bucket (<bucket>/*), and the matching S3 action ' +
    'groups (s3:GetObject*, s3:GetBucket*, s3:List*). Each names a single resource of this app.',
  appliesTo: [
    // The same resource in its two rendered forms: an attribute of a resource in the same
    // stack (<Table.Arn>) or a value exported by another stack of this app.
    { regex: '/^Resource::<[A-Za-z0-9]+\\.Arn>\\/index\\/\\*$/' },
    { regex: '/^Resource::<[A-Za-z0-9]+\\.Arn>\\/\\*$/' },
    { regex: '/^Resource::[A-Za-z0-9]+:ExportsOutputFnGetAtt[A-Za-z0-9]+Arn[A-Za-z0-9]+\\/index\\/\\*$/' },
    { regex: '/^Resource::[A-Za-z0-9]+:ExportsOutputFnGetAtt[A-Za-z0-9]+Arn[A-Za-z0-9]+\\/\\*$/' },
    'Action::s3:GetObject*',
    'Action::s3:GetBucket*',
    'Action::s3:List*',
  ],
};

/** `Resource: *` on one policy, for actions that IAM does not scope to a resource. */
function unscopableActions(stack: Stack, path: string, actions: string): void {
  NagSuppressions.addResourceSuppressionsByPath(stack, `/${stack.stackName}/${path}`, [
    {
      id: 'AwsSolutions-IAM5',
      reason: `${actions} do not support resource-level permissions, so IAM requires Resource: *.`,
      appliesTo: ['Resource::*'],
    },
  ]);
}

export function applyNagChecks(stacks: FleetStacks): void {
  const { data, network, compute, functions } = stacks;

  NagSuppressions.addResourceSuppressionsByPath(data, `/${data.stackName}/SubscriptionKey/Resource`, [
    {
      id: 'AwsSolutions-SMG4',
      reason:
        'The secret holds a Kiro subscription API key issued by Kiro, not by AWS. Secrets ' +
        'Manager cannot rotate it; the operator replaces the value when Kiro reissues the key.',
    },
  ]);
  NagSuppressions.addResourceSuppressionsByPath(data, `/${data.stackName}/LeasesTable/Resource`, [
    {
      id: 'AwsSolutions-DDB3',
      reason:
        'Leases are short-lived claims that expire within minutes and are rebuilt by running ' +
        'tasks. Restoring an old copy would restore stale claims, so point-in-time recovery ' +
        'has nothing useful to recover.',
    },
  ]);

  unscopableActions(network, 'PrefixListS3/CustomResourcePolicy/Resource', 'ec2:DescribeManagedPrefixLists');
  unscopableActions(network, 'PrefixListDynamoDb/CustomResourcePolicy/Resource', 'ec2:DescribeManagedPrefixLists');
  NagSuppressions.addStackSuppressions(network, [LAMBDA_BASIC]);
  NagSuppressions.addResourceSuppressionsByPath(network, `/${network.stackName}/EndpointSecurityGroup/Resource`, [
    {
      id: 'CdkNagValidationFailure',
      reason:
        'EC23 cannot evaluate the ingress source because it is the VPC CIDR, a deploy-time ' +
        'token. The rule allows port 443 from this VPC only, never 0.0.0.0/0.',
      appliesTo: ['AwsSolutions-EC23'],
    },
  ]);

  unscopableActions(compute, 'ExecutionRole/DefaultPolicy/Resource', 'ecr:GetAuthorizationToken');
  NagSuppressions.addStackSuppressions(compute, [
    SCOPED_WILDCARDS,
    {
      id: 'AwsSolutions-IAM5',
      reason:
        'The task reads only secrets under this app\'s own subscription prefix ' +
        '(<prefix>/subscription/*), one per pooled key; the set of keys changes at runtime.',
      appliesTo: [{ regex: '/^Resource::arn:<AWS::Partition>:secretsmanager:.*:secret:.*\\/subscription\\/\\*$/' }],
    },
    {
      id: 'AwsSolutions-IAM5',
      reason:
        'A task turns scale-in protection on and off for itself (ecs:UpdateTaskProtection). ' +
        'Task IDs are not known in advance, so the grant covers tasks in this app\'s cluster ' +
        'only (task/<cluster>/*).',
      appliesTo: [{ regex: '/^Resource::arn:<AWS::Partition>:ecs:.*:task\\/<[A-Za-z0-9]+>\\/\\*$/' }],
    },
  ]);
  NagSuppressions.addResourceSuppressionsByPath(compute, `/${compute.stackName}/WorkerTask/Resource`, [
    {
      id: 'AwsSolutions-ECS2',
      reason:
        'The environment variables are non-secret configuration (queue URL, table and bucket ' +
        'names, limits). Subscription keys are read from Secrets Manager at runtime.',
    },
  ]);

  unscopableActions(
    functions,
    'LogRetentionaae0aa3c5b4d4f87b02d85b201efdd8a/ServiceRole/DefaultPolicy/Resource',
    'logs:PutRetentionPolicy and logs:DeleteRetentionPolicy (CDK log retention handler)',
  );
  unscopableActions(functions, 'Reconciler/ServiceRole/DefaultPolicy/Resource', 'dynamodb:ListStreams');
  NagSuppressions.addResourceSuppressionsByPath(
    functions,
    `/${functions.stackName}/ScalingSignal/ServiceRole/DefaultPolicy/Resource`,
    [
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'DescribeScalableTargets and cloudwatch:DescribeAlarms are reads; the scale-in alarm ' +
          'is created by Application Auto Scaling under a generated name, so its ARN is not ' +
          'known at deploy time. RegisterScalableTarget is called only for the fleet\'s own ECS ' +
          'service (the function passes that service as the resource ID). ecs:DescribeServices ' +
          'is limited to this cluster by an ArnEquals condition.',
        appliesTo: ['Resource::*'],
      },
    ],
  );
  NagSuppressions.addStackSuppressions(functions, [LAMBDA_BASIC, SCOPED_WILDCARDS]);

  for (const stack of Object.values(stacks)) {
    Aspects.of(stack).add(new AwsSolutionsChecks({ verbose: true }));
  }
}
